-- DOMAIN-02: custom-domain write path and verification.
--
-- 1) Verification state on the tenant row. A custom domain is honoured (tenant resolution, CORS, OAuth2 redirects,
--    emailed links) ONLY while custom_domain_status = 'VERIFIED'.
-- 2) Case-insensitive uniqueness enforced by the database (uq_tenants_custom_domain_lower replaces the old
--    case-sensitive uq_tenants_custom_domain), plus shape checks so no code path can store a mixed-case, padded or
--    non-ASCII host.
-- 3) An append-only audit trail of every domain change (tenant_domain_audit_log).
--
-- Existing values (only ever set by direct DB edits; no code path wrote custom_domain before DOMAIN-02) are normalised
-- (trimmed, lower-cased, one trailing dot removed). A value that is still not a plain ASCII host, or that collides with
-- an older tenant's value after normalisation, is cleared. Every surviving legacy value becomes PENDING with a fresh
-- token: it stops being honoured until its owner proves control through the verify endpoint (fail safe).

ALTER TABLE tenants DROP CONSTRAINT uq_tenants_custom_domain;

ALTER TABLE tenants
    ADD COLUMN custom_domain_status       VARCHAR(20),
    ADD COLUMN custom_domain_token        VARCHAR(64),
    ADD COLUMN custom_domain_requested_at TIMESTAMP WITH TIME ZONE,
    ADD COLUMN custom_domain_checked_at   TIMESTAMP WITH TIME ZONE,
    ADD COLUMN custom_domain_verified_at  TIMESTAMP WITH TIME ZONE,
    ADD COLUMN custom_domain_failure      VARCHAR(40);

UPDATE tenants
SET custom_domain = NULLIF(regexp_replace(lower(btrim(custom_domain)), '\.$', ''), '')
WHERE custom_domain IS NOT NULL;

UPDATE tenants
SET custom_domain = NULL
WHERE custom_domain IS NOT NULL
  AND (custom_domain !~ '^[a-z0-9.-]{1,253}$' OR custom_domain LIKE '.%' OR custom_domain LIKE '%..%');

UPDATE tenants t
SET custom_domain = NULL
WHERE t.custom_domain IS NOT NULL
  AND EXISTS (SELECT 1 FROM tenants o WHERE o.custom_domain = t.custom_domain AND o.id < t.id);

UPDATE tenants
SET custom_domain_status       = 'PENDING',
    custom_domain_token        = md5(random()::text || clock_timestamp()::text || id::text),
    custom_domain_requested_at = now()
WHERE custom_domain IS NOT NULL;

CREATE UNIQUE INDEX uq_tenants_custom_domain_lower ON tenants (lower(custom_domain));

ALTER TABLE tenants
    ADD CONSTRAINT ck_tenants_custom_domain_shape
        CHECK (custom_domain IS NULL OR (custom_domain ~ '^[a-z0-9.-]{1,253}$'
            AND custom_domain NOT LIKE '.%' AND custom_domain NOT LIKE '%.' AND custom_domain NOT LIKE '%..%')),
    ADD CONSTRAINT ck_tenants_custom_domain_status
        CHECK (custom_domain_status IS NULL OR custom_domain_status IN ('PENDING', 'VERIFIED', 'FAILED')),
    -- a domain always carries a status and a token; no domain means no verification state at all
    ADD CONSTRAINT ck_tenants_custom_domain_state
        CHECK ((custom_domain IS NULL AND custom_domain_status IS NULL AND custom_domain_token IS NULL)
            OR (custom_domain IS NOT NULL AND custom_domain_status IS NOT NULL AND custom_domain_token IS NOT NULL));

-- Append-only audit of custom-domain changes. Like tenant_audit_log: identifiers only, no FK on tenant_id (a purged
-- tenant must not erase its history), UPDATE/DELETE/TRUNCATE rejected by triggers.
--   actor_type  TENANT_ADMIN (actor_id = the tenant's users.id), PLATFORM_ADMIN (platform_admins.id) or SYSTEM
--               (a stale PENDING/FAILED claim released when another tenant claims the domain; actor_id/email NULL).
--   action      REQUEST (claim or replace; previous_domain set on a replace), VERIFY (one row per completed DNS
--               check, outcome in new_status/detail), REMOVE, RELEASE.
CREATE TABLE tenant_domain_audit_log
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE                NOT NULL DEFAULT now(),
    actor_type      VARCHAR(20)                             NOT NULL,
    actor_id        BIGINT,
    actor_email     VARCHAR(255),
    tenant_id       BIGINT                                  NOT NULL,
    tenant_slug     VARCHAR(40)                             NOT NULL,
    action          VARCHAR(20)                             NOT NULL,
    domain          VARCHAR(253)                            NOT NULL,
    previous_domain VARCHAR(253),
    previous_status VARCHAR(20),
    new_status      VARCHAR(20),
    detail          VARCHAR(40),
    CONSTRAINT pk_tenant_domain_audit_log PRIMARY KEY (id),
    CONSTRAINT ck_tenant_domain_audit_actor CHECK (actor_type IN ('TENANT_ADMIN', 'PLATFORM_ADMIN', 'SYSTEM')),
    CONSTRAINT ck_tenant_domain_audit_action CHECK (action IN ('REQUEST', 'VERIFY', 'REMOVE', 'RELEASE'))
);

CREATE INDEX idx_tenant_domain_audit_tenant ON tenant_domain_audit_log (tenant_id, occurred_at);

CREATE FUNCTION tenant_domain_audit_log_immutable() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'tenant_domain_audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_tenant_domain_audit_log_no_update_delete
    BEFORE UPDATE OR DELETE ON tenant_domain_audit_log
    FOR EACH ROW EXECUTE FUNCTION tenant_domain_audit_log_immutable();

CREATE TRIGGER trg_tenant_domain_audit_log_no_truncate
    BEFORE TRUNCATE ON tenant_domain_audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION tenant_domain_audit_log_immutable();
