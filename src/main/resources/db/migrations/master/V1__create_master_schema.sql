-- Master (control-plane) schema. Applied by TenantSchemaMigrator.migrateMaster()
-- with Flyway defaultSchema=master, so these unqualified tables land in `master`.

-- Tenant registry: one row per shop/tenant.
CREATE TABLE tenants
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    slug          VARCHAR(40)                             NOT NULL,
    display_name  VARCHAR(255)                            NOT NULL,
    schema_name   VARCHAR(63)                             NOT NULL,
    status        VARCHAR(20)                             NOT NULL,
    plan          VARCHAR(20)                             NOT NULL,
    owner_email   VARCHAR(255)                            NOT NULL,
    custom_domain VARCHAR(255),
    created_at    TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_tenants PRIMARY KEY (id),
    CONSTRAINT uq_tenants_slug UNIQUE (slug),
    CONSTRAINT uq_tenants_schema_name UNIQUE (schema_name),
    CONSTRAINT uq_tenants_custom_domain UNIQUE (custom_domain),
    CONSTRAINT uq_tenants_owner_email UNIQUE (owner_email)
);

CREATE INDEX idx_tenants_status ON tenants (status);

-- Platform super-admins (separate from per-tenant users).
CREATE TABLE platform_admins
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email      VARCHAR(255)                            NOT NULL,
    password   VARCHAR(255)                            NOT NULL,
    full_name  VARCHAR(255)                            NOT NULL,
    is_active  BOOLEAN                                 NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_platform_admins PRIMARY KEY (id),
    CONSTRAINT uq_platform_admins_email UNIQUE (email)
);

-- Deterministic webhook routing: maps a payment reference to its owning tenant so an
-- async Paystack callback (which carries no cookie/host) can resolve the tenant schema
-- without scanning every tenant. Written at payment init; provider_reference filled
-- after Paystack initiation.
CREATE TABLE payment_tenant_routes
(
    system_reference   VARCHAR(255)               NOT NULL,
    provider_reference VARCHAR(255),
    tenant_slug        VARCHAR(40)                NOT NULL,
    schema_name        VARCHAR(63)                NOT NULL,
    created_at         TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_payment_tenant_routes PRIMARY KEY (system_reference),
    CONSTRAINT uq_payment_tenant_routes_provider_reference UNIQUE (provider_reference)
);

CREATE INDEX idx_payment_tenant_routes_provider_reference
    ON payment_tenant_routes (provider_reference);
