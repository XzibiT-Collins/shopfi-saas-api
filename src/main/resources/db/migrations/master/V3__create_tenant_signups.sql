-- PROV-02: pending onboarding state. One row per not-yet-provisioned tenant, deleted once provisioning
-- succeeds. Holds ONLY a BCrypt hash of the owner's password (never plaintext) and a salted SHA-256 of the
-- emailed OTP (never the OTP itself), plus the attempt/lockout counters that enforce the OTP attempt cap.
CREATE TABLE tenant_signups
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tenant_id       BIGINT                                  NOT NULL,
    owner_full_name VARCHAR(255)                            NOT NULL,
    password_hash   VARCHAR(100)                            NOT NULL,
    otp_salt        VARCHAR(64)                             NOT NULL,
    otp_hash        VARCHAR(64)                             NOT NULL,
    otp_expires_at  TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    failed_attempts INTEGER                                 NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP WITHOUT TIME ZONE,
    verified_at     TIMESTAMP WITHOUT TIME ZONE,
    created_at      TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_tenant_signups PRIMARY KEY (id),
    CONSTRAINT uq_tenant_signups_tenant UNIQUE (tenant_id),
    CONSTRAINT fk_tenant_signups_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE
);
