-- PLAT-02: append-only audit trail of platform-admin actions on tenants (approve/suspend/reactivate/reprovision).
-- Holds identifiers and statuses only: never passwords, hashes, tokens or request bodies. tenant_id has NO foreign
-- key on purpose (a purged tenant row must not erase or block its history); tenant_slug is kept for readability.
CREATE TABLE tenant_audit_log
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    occurred_at     TIMESTAMP WITH TIME ZONE                NOT NULL DEFAULT now(),
    actor_admin_id  BIGINT                                  NOT NULL,
    actor_email     VARCHAR(255)                            NOT NULL,
    tenant_id       BIGINT                                  NOT NULL,
    tenant_slug     VARCHAR(40)                             NOT NULL,
    action          VARCHAR(20)                             NOT NULL,
    previous_status VARCHAR(20)                             NOT NULL,
    new_status      VARCHAR(20)                             NOT NULL,
    CONSTRAINT pk_tenant_audit_log PRIMARY KEY (id),
    CONSTRAINT ck_tenant_audit_log_action CHECK (action IN ('APPROVE', 'SUSPEND', 'REACTIVATE', 'REPROVISION'))
);

CREATE INDEX idx_tenant_audit_log_tenant ON tenant_audit_log (tenant_id, occurred_at);

-- Tamper resistance: rows can be inserted and read, never changed or removed through SQL issued by the application
-- (the code has no update/delete path either). Row triggers block UPDATE/DELETE, a statement trigger blocks TRUNCATE.
CREATE FUNCTION tenant_audit_log_immutable() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'tenant_audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_tenant_audit_log_no_update_delete
    BEFORE UPDATE OR DELETE ON tenant_audit_log
    FOR EACH ROW EXECUTE FUNCTION tenant_audit_log_immutable();

CREATE TRIGGER trg_tenant_audit_log_no_truncate
    BEFORE TRUNCATE ON tenant_audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION tenant_audit_log_immutable();
