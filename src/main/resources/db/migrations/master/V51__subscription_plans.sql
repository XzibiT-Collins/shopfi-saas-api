-- PLAN-01: configurable subscription plans (contract docs/api/plans.md, PLAN-03).
-- The code defines WHICH features exist (PlanFeature enum); this data says which plan has which feature or limit, the
-- price, trial and card text. The annual price is never stored: it is derived from monthly_price_pesewas and
-- annual_discount_percent by one server function (owner O5).

CREATE TABLE plans
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code                    VARCHAR(32)                             NOT NULL,
    name                    VARCHAR(40)                             NOT NULL,
    tagline                 VARCHAR(40),
    description             VARCHAR(280),
    monthly_price_pesewas   BIGINT                                  NOT NULL,
    annual_discount_percent SMALLINT                                NOT NULL,
    currency                VARCHAR(3)                              NOT NULL DEFAULT 'GHS',
    trial_days              INTEGER                                 NOT NULL,
    transaction_fee_bps     INTEGER                                 NOT NULL,
    is_public               BOOLEAN                                 NOT NULL,
    is_default_for_signup   BOOLEAN                                 NOT NULL DEFAULT FALSE,
    highlighted             BOOLEAN                                 NOT NULL DEFAULT FALSE,
    badge_label             VARCHAR(40),
    bullets_heading         VARCHAR(80),
    marketing_bullets       JSONB                                   NOT NULL DEFAULT '[]'::jsonb,
    sort_order              INTEGER                                 NOT NULL,
    active                  BOOLEAN                                 NOT NULL,
    version                 BIGINT                                  NOT NULL DEFAULT 0,
    updated_at              TIMESTAMP WITH TIME ZONE                NOT NULL DEFAULT now(),
    updated_by              VARCHAR(255),
    CONSTRAINT pk_plans PRIMARY KEY (id),
    CONSTRAINT uq_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_code CHECK (code ~ '^[A-Z][A-Z0-9_]{1,31}$'),
    CONSTRAINT ck_plans_monthly_price CHECK (monthly_price_pesewas BETWEEN 0 AND 100000000),
    CONSTRAINT ck_plans_annual_discount CHECK (annual_discount_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_plans_currency CHECK (currency = 'GHS'),
    CONSTRAINT ck_plans_trial_days CHECK (trial_days BETWEEN 0 AND 365),
    CONSTRAINT ck_plans_fee CHECK (transaction_fee_bps BETWEEN 0 AND 1000),
    CONSTRAINT ck_plans_sort_order CHECK (sort_order BETWEEN 0 AND 1000),
    CONSTRAINT ck_plans_bullets CHECK (jsonb_typeof(marketing_bullets) = 'array' AND jsonb_array_length(marketing_bullets) <= 12),
    CONSTRAINT ck_plans_version CHECK (version >= 0),
    -- the default sign-up plan is active and has a trial (plans.md section 7); the service checks it first with a field message
    CONSTRAINT ck_plans_default_signup CHECK (NOT is_default_for_signup OR (active AND trial_days >= 1))
);

-- At most one default sign-up plan (the service keeps exactly one; moving the flag clears the old one first).
CREATE UNIQUE INDEX uq_plans_default_for_signup ON plans ((TRUE)) WHERE is_default_for_signup;

-- Entitlements: one row per (plan, feature key). A catalog key without a row reads as off / 0; a stored key that is not
-- in the PlanFeature enum is ignored on read. limit_value NULL = unlimited (LIMIT features); always NULL for BOOLEAN ones.
CREATE TABLE plan_entitlements
(
    plan_id     BIGINT      NOT NULL,
    feature_key VARCHAR(64) NOT NULL,
    enabled     BOOLEAN     NOT NULL,
    limit_value INTEGER,
    CONSTRAINT pk_plan_entitlements PRIMARY KEY (plan_id, feature_key),
    CONSTRAINT fk_plan_entitlements_plan FOREIGN KEY (plan_id) REFERENCES plans (id),
    CONSTRAINT ck_plan_entitlements_limit CHECK (limit_value IS NULL OR limit_value >= 0)
);

-- Append-only audit of every plan create / update / matrix change and every tenant plan change (plans.md section 10).
-- actor_admin_id is the immutable platform admin id (not returned by the API). No foreign keys on purpose, like
-- tenant_audit_log: history must survive whatever happens to the rows it describes.
CREATE TABLE plan_audit_log
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    occurred_at    TIMESTAMP WITH TIME ZONE                NOT NULL DEFAULT now(),
    actor_admin_id BIGINT                                  NOT NULL,
    actor_email    VARCHAR(255)                            NOT NULL,
    action         VARCHAR(30)                             NOT NULL,
    plan_id        BIGINT,
    plan_code      VARCHAR(32),
    tenant_id      BIGINT,
    tenant_slug    VARCHAR(40),
    changes        JSONB                                   NOT NULL,
    CONSTRAINT pk_plan_audit_log PRIMARY KEY (id),
    CONSTRAINT ck_plan_audit_log_action CHECK (action IN ('PLAN_CREATE', 'PLAN_UPDATE', 'PLAN_MATRIX_UPDATE', 'TENANT_PLAN_UPDATE')),
    CONSTRAINT ck_plan_audit_log_changes CHECK (jsonb_typeof(changes) = 'array' AND jsonb_array_length(changes) >= 1),
    CONSTRAINT ck_plan_audit_log_tenant CHECK ((action = 'TENANT_PLAN_UPDATE') = (tenant_slug IS NOT NULL))
);

CREATE INDEX idx_plan_audit_log_plan ON plan_audit_log (plan_id, id);
CREATE INDEX idx_plan_audit_log_tenant ON plan_audit_log (tenant_slug, id);

CREATE FUNCTION plan_audit_log_immutable() RETURNS trigger AS
$$
BEGIN
    RAISE EXCEPTION 'plan_audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_plan_audit_log_no_update_delete
    BEFORE UPDATE OR DELETE ON plan_audit_log
    FOR EACH ROW EXECUTE FUNCTION plan_audit_log_immutable();

CREATE TRIGGER trg_plan_audit_log_no_truncate
    BEFORE TRUNCATE ON plan_audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION plan_audit_log_immutable();

