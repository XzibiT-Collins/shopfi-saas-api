-- ---------------------------------------------------------------------------------------------------- tenants
-- plan_id replaces the free-text plan column. Backfill (board AC2): FREE and STARTER -> STARTER, PRO -> SCALE. There is no
-- ELSE branch on purpose: an unknown legacy value leaves plan_id NULL and the SET NOT NULL below fails the migration
-- instead of silently picking a plan.
ALTER TABLE tenants
    ADD COLUMN plan_id             BIGINT,
    ADD COLUMN subscription_status VARCHAR(20)              NOT NULL DEFAULT 'TRIALING',
    ADD COLUMN trial_ends_at       TIMESTAMP WITH TIME ZONE;

UPDATE tenants
SET plan_id = CASE plan
                  WHEN 'FREE' THEN 1
                  WHEN 'STARTER' THEN 1
                  WHEN 'PRO' THEN 3
    END;

-- Backfilled tenants start a 14-day trial (board AC2). Only tenants that finished provisioning (ACTIVE, SUSPENDED) get
-- a trial end now; a PENDING / PROVISIONING / FAILED tenant keeps NULL and gets it when provisioning first completes
-- (plans.md section 15, platform-tenants.md: trialEndsAt is null while the tenant has not finished provisioning).
UPDATE tenants
SET trial_ends_at = now() + INTERVAL '14 days'
WHERE status IN ('ACTIVE', 'SUSPENDED');

ALTER TABLE tenants
    ALTER COLUMN plan_id SET NOT NULL,
    ADD CONSTRAINT fk_tenants_plan FOREIGN KEY (plan_id) REFERENCES plans (id),
    ADD CONSTRAINT ck_tenants_subscription_status CHECK (subscription_status IN ('TRIALING', 'ACTIVE', 'PAST_DUE', 'CANCELED'));

CREATE INDEX idx_tenants_plan_status ON tenants (plan_id, subscription_status);

ALTER TABLE tenants
    DROP COLUMN plan;

-- ---------------------------------------------------------------------------------------------------- tenant audit
-- A tenant plan / trial / subscription change is also a tenant audit row (plans.md section 11): action CHANGE_PLAN,
-- phase OUTCOME, previous_status = new_status = the registry status. Re-creating the CHECK touches no row (the V6
-- append-only triggers fire on UPDATE / DELETE / TRUNCATE only).
ALTER TABLE tenant_audit_log
    DROP CONSTRAINT ck_tenant_audit_log_action;

ALTER TABLE tenant_audit_log
    ADD CONSTRAINT ck_tenant_audit_log_action
        CHECK (action IN ('APPROVE', 'SUSPEND', 'REACTIVATE', 'REPROVISION', 'CHANGE_PLAN'));
