-- Per-tenant payment gateway credentials (the tenant's own Paystack account).
-- Singleton row per tenant schema. Secret key is stored AES-GCM encrypted, never plaintext.
CREATE TABLE payment_gateway_config
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    provider             VARCHAR(20)                             NOT NULL,
    secret_key_encrypted TEXT,
    public_key           VARCHAR(255),
    enabled              BOOLEAN                                 NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at           TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_payment_gateway_config PRIMARY KEY (id)
);
