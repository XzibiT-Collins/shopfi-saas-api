-- Per-tenant storefront theme (THEME-01). Singleton row per tenant schema.
-- `theme` holds exactly the theme document defined in docs/api/theme-contract.md and
-- docs/api/theme.schema.json (schemaVersion + tokens + assets + pages). `version` is the optimistic-lock
-- counter used for ETag / If-Match. The default row below is the contract's "default-new-tenant" example;
-- a test (StoreSettingsMigrationDefaultTest) keeps the two in sync. Because this migration runs for
-- tenant_template, every new tenant (provisioning's migrate) and every existing tenant (migrateTenant at
-- boot) receives the default row without any provisioning code.
CREATE TABLE store_settings
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    schema_version INTEGER                                 NOT NULL,
    theme          JSONB                                   NOT NULL,
    version        BIGINT                                  NOT NULL DEFAULT 1,
    created_at     TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    updated_at     TIMESTAMP WITHOUT TIME ZONE,
    updated_by     VARCHAR(255),
    CONSTRAINT pk_store_settings PRIMARY KEY (id)
);

