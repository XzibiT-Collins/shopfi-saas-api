-- ORD-01: admin order handling. Additive only (no applied migration is edited).

-- Optimistic concurrency for admin status changes (JPA @Version; every order write bumps it).
ALTER TABLE orders ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

-- Who/when/how an order was cancelled. cancel_source: CUSTOMER | ADMIN | EXPIRY (null for orders cancelled before
-- ORD-01). cancelled_by holds the acting admin's e-mail only (no other personal data).
ALTER TABLE orders ADD COLUMN cancelled_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE orders ADD COLUMN cancelled_by VARCHAR(255);
ALTER TABLE orders ADD COLUMN cancel_source VARCHAR(16);

-- Current state of the manual-refund hand-off (the append-only history is order_audit_events).
ALTER TABLE payments ADD COLUMN refund_acknowledged_at TIMESTAMP WITHOUT TIME ZONE;
ALTER TABLE payments ADD COLUMN refund_acknowledged_by VARCHAR(255);

-- Append-only audit trail of admin actions on an order: rows are only ever inserted by the application.
CREATE TABLE order_audit_events
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_id        BIGINT                                  NOT NULL,
    event_type      VARCHAR(32)                             NOT NULL,
    from_status     VARCHAR(32),
    to_status       VARCHAR(32),
    refund_required BOOLEAN                                 NOT NULL DEFAULT FALSE,
    actor_email     VARCHAR(255)                            NOT NULL,
    created_at      TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_order_audit_events PRIMARY KEY (id),
    CONSTRAINT fk_order_audit_events_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);
CREATE INDEX idx_order_audit_events_order ON order_audit_events (order_id, id);

-- Atomic claim of a generated order number: INSERT ... ON CONFLICT DO NOTHING tells concurrent checkouts apart
-- without poisoning their transaction (orders.order_number stays UNIQUE as the final backstop).
CREATE TABLE order_number_claims
(
    order_number VARCHAR(64)                 NOT NULL,
    claimed_at   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT pk_order_number_claims PRIMARY KEY (order_number)
);

-- Admin list: default sort and date-range filter.
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders (created_at);
